$found = New-Object System.Collections.Generic.List[string]
foreach ($file in $cultureFiles) {
    if (-not (Test-Path $file)) { continue }
    foreach ($line in Get-Content $file) {
        if ($line -match '^([a-z0-9_]+) = \{') { $found.Add($Matches[1]) }
    }
}

$missing = @()
$out = New-Object System.Collections.Generic.List[string]
$out.Add("# Etnias generadas: cada cultura del mod usa una etnia vanilla de CK3.")
$out.Add("# Los retratos se renderizan con el sistema de retratos del juego base (ya no low poly).")
$out.Add("")
foreach ($c in $found) {
    if ($map.ContainsKey($c)) {
        $out.Add("$c = {")
        $out.Add("`ttemplate = `"$($map[$c])`"")
        $out.Add("}")
    }
    else {
        $missing += $c
        $out.Add("$c = {")
        $out.Add("`ttemplate = `"caucasian`"")
        $out.Add("}")
    }
}

$target = "$root\common\ethnicities\zz_ckow_vanilla_ethnicities.txt"
Set-Content -Path $target -Value $out -Encoding UTF8
Write-Host "Culturas encontradas: $($found.Count)"
Write-Host "Generadas: $($found.Count - $missing.Count) mapeadas + $($missing.Count) por defecto"
Write-Host "Sin mapeo explicito (caucasian): $($missing -join ', ')"
Write-Host "Archivo: $target"


